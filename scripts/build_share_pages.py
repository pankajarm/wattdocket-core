"""Stage historical preview artifacts and safe redirects to the current app.

Each preview names one ECHO record and links to the existing public card. No
facility measurements are inferred. The generated CloudFront viewer-request
function redirects known historical links before they can expose old metadata,
and rejects unknown IDs before S3's custom-error fallback. Attach it only to
the /share/* behavior. Current production copy links point directly to the app.
"""
from __future__ import annotations

import argparse
import html
import json
import re
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent
ID = re.compile(r'^echo:([A-Za-z0-9]{1,30})(?:-(\d+))?$')
ORIGIN = 'https://wattdocket.com'


def page(entry: dict, card: dict) -> tuple[str, str]:
    match = ID.fullmatch(entry.get('id', ''))
    if not match:
        raise ValueError(f"Invalid facility ID: {entry.get('id')!r}")
    suffix = f'-{match[2]}' if match[2] else ''
    slug = f'echo_{match[1].lower()}{suffix}'
    facility = card['facility']
    expected_card_id = slug
    if str(facility.get('id', '')).lower() != expected_card_id:
        raise ValueError(f'{slug}: index and card IDs differ')
    for index_key, card_key in [('name', 'name'), ('address_line', 'address'), ('city', 'city'), ('state', 'state')]:
        if (entry.get(index_key) or '').strip() != (facility.get(card_key) or '').strip():
            raise ValueError(f'{slug}: index and card disagree on {index_key}')
    name = (facility.get('name') or '').strip()
    if not name:
        raise ValueError(f'{slug}: missing facility name')
    location = ', '.join(v for v in (facility.get('city'), facility.get('state')) if v)
    date = str(card.get('as_of', ''))[:10]
    if not re.fullmatch(r'\d{4}-\d{2}-\d{2}', date):
        raise ValueError(f'{slug}: missing snapshot date')
    title = f'{name} | WattDocket'
    description = f"Explore public records for {name}{f' in {location}' if location else ''}. Snapshot {date}. Estimates are not facility measurements."
    canonical = f'{ORIGIN}/share/{slug}.html'
    app_path = '/app/index.html#/public/' + quote(entry['id'], safe='')
    esc = lambda text: html.escape(text, quote=True)
    out = f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)}</title><meta name="description" content="{esc(description)}">
<link rel="canonical" href="{esc(canonical)}">
<meta property="og:type" content="website"><meta property="og:site_name" content="WattDocket">
<meta property="og:title" content="{esc(title)}"><meta property="og:description" content="{esc(description)}">
<meta property="og:url" content="{esc(canonical)}"><meta property="og:image" content="{ORIGIN}/app/share-preview.png">
<meta property="og:image:width" content="1200"><meta property="og:image:height" content="630"><meta property="og:image:alt" content="WattDocket: Public records, in perspective">
<meta name="twitter:card" content="summary_large_image"><meta name="twitter:title" content="{esc(title)}"><meta name="twitter:description" content="{esc(description)}"><meta name="twitter:image" content="{ORIGIN}/app/share-preview.png">
<script>window.location.replace({json.dumps(app_path)});</script></head>
<body><p>Opening the public record for {esc(name)}. <a href="{esc(app_path)}">View this facility on WattDocket</a>.</p></body></html>\n'''
    return slug, out


def edge_function(slugs: list[str]) -> str:
    ids = '|'.join(slug.removeprefix('echo_') for slug in sorted(slugs))
    # The surrounding delimiters prevent substring matches between sibling IDs.
    return '''// Generated by scripts/build_share_pages.py; attach only to /share/*.
function handler(event) {
  var req = event.request, uri = req.uri;
  if (req.headers && req.headers.host && req.headers.host.value.toLowerCase() === 'www.wattdocket.com') {
    var raw = typeof req.rawQueryString === 'function' ? req.rawQueryString() : undefined;
    return {statusCode: 308, statusDescription: 'Permanent Redirect', headers: {location: {value: 'https://wattdocket.com' + uri + (raw === undefined ? '' : '?' + raw)}}};
  }
  var match = /^\\/share\\/echo_([a-z0-9]{1,30}(?:-\\d+)?)\\.html$/.exec(uri);
  var ids = '|''' + ids + '''|';
  if (!match || ids.indexOf('|' + match[1] + '|') < 0) {
    return {statusCode: 404, statusDescription: 'Not Found', headers: {'content-type': {value: 'text/plain; charset=utf-8'}, 'cache-control': {value: 'no-store'}}, body: {encoding: 'text', data: 'Facility preview not found.'}};
  }
  return {statusCode: 302, statusDescription: 'Found', headers: {location: {value: '/app/index.html#/public/echo%3A' + match[1]}, 'cache-control': {value: 'public, max-age=300'}}};
}
'''


def build(index_path: Path, cards_dir: Path, output: Path, function_path: Path) -> int:
    entries = json.loads(index_path.read_text(encoding='utf-8'))
    if not isinstance(entries, list) or not entries:
        raise ValueError('Facility index is empty or malformed')
    rendered = {}
    for entry in entries:
        match = ID.fullmatch(entry.get('id', ''))
        if not match:
            raise ValueError(f"Invalid facility ID: {entry.get('id')!r}")
        key = 'echo_' + match[1].lower() + ('_' + match[2] if match[2] else '')
        card = json.loads((cards_dir / key).read_text(encoding='utf-8'))
        slug, text = page(entry, card)
        if slug in rendered:
            raise ValueError(f'Duplicate preview: {slug}')
        rendered[slug] = text
    function = edge_function(list(rendered))
    if len(function.encode('utf-8')) > 10 * 1024:
        raise ValueError('Share function exceeds the CloudFront Functions 10 KB limit')
    # All data is validated before replacing generated artifacts.
    output.mkdir(parents=True, exist_ok=True)
    for old in output.glob('echo_*.html'):
        old.unlink()
    for slug, text in rendered.items():
        (output / f'{slug}.html').write_text(text, encoding='utf-8')
    function_path.parent.mkdir(parents=True, exist_ok=True)
    function_path.write_text(function, encoding='utf-8')
    return len(rendered)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--index', type=Path, default=ROOT / 'site/api/facilities')
    parser.add_argument('--cards', type=Path, default=ROOT / 'site/api/card')
    parser.add_argument('--out', type=Path, default=ROOT / 'site/share')
    parser.add_argument('--function', type=Path, default=ROOT / 'site/share-viewer-request.js')
    args = parser.parse_args()
    print(f'Generated {build(args.index, args.cards, args.out, args.function)} share pages and viewer-request allowlist.')
